using System.Threading.Tasks;
using Workspace1C.Models;

namespace Workspace1C.Services;

/// <summary>
/// Подсистема автообновления приложения: скачивание и применение новой версии,
/// которую использует планировщик заданий для <see cref="ScheduledTaskKind.UpdateApp"/>.
/// Выделена в интерфейс, чтобы <see cref="SchedulerService"/> оставался тестируемым
/// (фейк в Workspace1C.Tests); платформенные реализации — WPF и Avalonia
/// (<see cref="UpdateService"/>, общий тип с разной реализацией по #if WINDOWS/#if LINUX).
/// </summary>
public interface IAppUpdateService
{
    /// Скачивает новый исполняемый файл и применяет обновление (при необходимости
    /// перезапускает приложение). Ошибки скачивания/применения обрабатываются внутри
    /// реализацией и наружу не выбрасываются.
    /// </summary>
    /// <returns>
    /// <c>true</c>, если обновление реально применено: новый исполняемый файл скачан,
    /// помощник запущен, записан маркер <c>pending_update.json</c> и приложение будет
    /// перезапущено с новой версией. <c>false</c> — если применить не удалось (нет
    /// адреса загрузки, сбой скачивания/замены, невозможность самообновления).
    /// Планировщик использует результат для подавления уведомления «задание выполнено»
    /// (issue #10): при успешном применении обновление сообщает о себе само —
    /// уведомлением «Приложение обновлено до версии X» из новой версии при старте.
    /// </returns>
    Task<bool> DownloadAndInstallAutoAsync(ReleaseInfo release);
}